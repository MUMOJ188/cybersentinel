import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export interface ReportExport {
  period: "daily" | "weekly" | "monthly";
  period_label: string;
  generated_at: string;
  range_start: string;
  range_end: string;
  total_security_events: number;
  total_alerts: number;
  critical_alerts: number;
  high_alerts: number;
  new_incidents: number;
  resolved_incidents: number;
  average_response_time_seconds: number | null;
  most_common_alert_type: string;
}

function fmt(dateIso: string) {
  return new Date(dateIso).toLocaleString();
}

function fmtDuration(seconds: number | null) {
  if (seconds == null) return "N/A";
  const h = Math.floor(seconds / 3600);
  const m = Math.round((seconds % 3600) / 60);
  return h > 0 ? `${h}h ${m}m` : `${m}m`;
}

/**
 * Builds and downloads a PDF report, following the same layout shape as
 * the organization's existing daily-report template: company header,
 * "Generated" / "Period" lines, a Summary Highlights table, then a
 * footer with contact info, "Generated by" line, date, and a signature
 * line. Only the body metrics are CyberSentinel-specific.
 */
export function generateReportPdf(data: ReportExport) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.text("CYBERSENTINEL", pageWidth / 2, 18, { align: "center" });

  doc.setFontSize(12);
  doc.text(`${data.period_label} Report`, pageWidth / 2, 26, { align: "center" });

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Generated: ${fmt(data.generated_at)}`, pageWidth / 2, 33, { align: "center" });
  doc.text(`Period: ${fmt(data.range_start)} — ${fmt(data.range_end)}`, pageWidth / 2, 39, { align: "center" });

  doc.setDrawColor(200);
  doc.line(14, 44, pageWidth - 14, 44);

  // Summary Highlights
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Summary Highlights", 14, 54);

  const rows: [string, string][] = [
    ["Total Security Events", String(data.total_security_events)],
    ["Total Alerts", String(data.total_alerts)],
    ["Critical Alerts", String(data.critical_alerts)],
    ["High Alerts", String(data.high_alerts)],
    ["New Incidents", String(data.new_incidents)],
    ["Resolved Incidents", String(data.resolved_incidents)],
    ["Average Response Time", fmtDuration(data.average_response_time_seconds)],
    ["Most Common Alert Type", data.most_common_alert_type]
  ];

  autoTable(doc, {
    startY: 59,
    head: [["Metric", "Value"]],
    body: rows,
    theme: "grid",
    headStyles: { fillColor: [30, 41, 59] }, // slate-800, matches app theme
    styles: { fontSize: 10 }
  });

  // Footer
  const finalY = (doc as any).lastAutoTable.finalY ?? 100;
  const footerY = Math.max(finalY + 20, 230);

  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text("CyberSentinel", 14, footerY);
  doc.setFont("helvetica", "normal");
  doc.text("Cybersecurity Monitoring & Incident Management System", 14, footerY + 5);

  doc.text(`Generated by CyberSentinel System`, 14, footerY + 15);
  doc.text(`Date: ${fmt(data.generated_at)}`, 14, footerY + 20);

  doc.text("Authorized Signature: ____________________________", 14, footerY + 32);

  doc.save(`cybersentinel-${data.period}-report-${new Date().toISOString().slice(0, 10)}.pdf`);
}